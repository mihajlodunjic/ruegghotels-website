test('contact validates, prepares and copies a local enquiry without delivery or storage', async ({ page, context }, info) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const writes: string[] = []
  page.on('request', (request) => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) writes.push(request.url()) })
  await page.goto('/contact?hotel=agnes&category=group')
  await page.getByRole('button', { name: 'Prepare your enquiry' }).click()
  await expect(page.getByLabel('Your name', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Your name', { exact: true }).fill('Alex Example')
  await page.getByLabel('Email', { exact: true }).fill('alex@example.com')
  await page.getByLabel('Your message', { exact: true }).fill('We would love to plan a mountain stay with our walking group next spring.')
  await page.getByRole('button', { name: 'Prepare your enquiry' }).click()
  await expect(page.getByText('Prepared locally on this device.', { exact: false })).toBeVisible()
  await expect(page.getByLabel('Your prepared enquiry')).toHaveValue(/Group travel/)
  await shot(page, info, 'contact-review')
  await page.getByRole('button', { name: 'Copy enquiry', exact: false }).click()
  await expect(page.getByRole('status')).toHaveText(/Copied to your clipboard.*not been sent/)
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('Alex Example')
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  expect(writes).toEqual([])
  await page.getByRole('button', { name: 'Start a new enquiry' }).click()
  await expect(page.getByLabel('Your name', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Your message', { exact: true })).toHaveValue('')
})
