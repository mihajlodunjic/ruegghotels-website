import { test, expect, type Page, type TestInfo } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdir } from 'node:fs/promises'
import { addDays, todayISO } from '../../src/features/booking/bookingModel'
const root = process.env.RUEGG_EVIDENCE_ROOT || 'docs/evidence/package-03'
async function shot(page: Page, info: TestInfo, name: string, fullPage = true) {
  await expect(page.locator('[data-page-ready]')).toHaveAttribute('data-page-ready', 'true')
  const panel = page.locator('[data-step-ready]')
  if (await panel.count()) await expect(panel).toHaveAttribute('data-step-ready', 'true')
  await page.evaluate(() => document.fonts.ready)
  await mkdir(root, { recursive: true })
  await page.screenshot({ path: `${root}/${info.project.name}-${name}.png`, fullPage, animations: 'disabled' })
}
const bookingStep = (page: Page, step: string) => expect(page.locator('[data-booking-step]')).toHaveAttribute('data-booking-step', step)

test('supporting pages share navigation, metadata, footer and editorial layouts', async ({ page }, info) => {
  const errors: string[] = []
  const videos: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => { if (request.url().includes('.mp4')) videos.push(request.url()) })
  for (const [route, name] of [['/partners', 'partners'], ['/book?hotel=agnes', 'book'], ['/our-story', 'story'], ['/contact', 'contact']]) {
    await page.goto(route)
    await expect(page.locator('h1')).toBeVisible()
    await expect(page).toHaveTitle(/RÜEGG HOTELS/)
    expect(await page.locator('meta[name="description"]').getAttribute('content')).toBeTruthy()
    await expect(page.getByRole('navigation', { name: 'Footer navigation' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await shot(page, info, name)
    if (name === 'partners') await expect(page.locator('[data-filter-ready]')).toHaveAttribute('data-filter-ready', 'true')
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.screenshot({ path: `${root}/${info.project.name}-${name}-fold.png`, fullPage: false, animations: 'disabled' })
  }
  await page.getByRole('button', { name: 'Menu', exact: false }).click()
  await expect(page.getByRole('dialog')).toHaveAttribute('data-menu-ready', 'true')
  await page.getByRole('dialog').getByRole('link', { name: /Our story/ }).click()
  await expect(page).toHaveURL(/our-story$/)
  await page.goBack()
  await expect(page).toHaveURL(/contact$/)
  await expect(page.locator('[data-page-ready]')).toHaveAttribute('data-page-ready', 'true')
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations).toEqual([])
  expect(errors).toEqual([])
  expect(videos).toEqual([])
})

test('hotel preselection and deterministic reservation complete without transactions', async ({ page }, info) => {
  const writes: string[] = []
  page.on('request', (request) => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) writes.push(request.url()) })
  const today = todayISO()
  const arrival = addDays(today, 30)
  const year = Number(today.slice(0, 4))
  const closedDate = [`${year}-12-24`, `${year}-12-25`, `${year + 1}-12-24`].find((day) => day >= today)!
  await page.goto('/book?hotel=schiebel')
  await expect(page.getByRole('radio', { name: /Schiebel/ })).toBeChecked()
  await page.getByRole('button', { name: 'Clear dates', exact: true }).click()
  await expect(page.getByLabel('Arrival', { exact: true })).toHaveValue('')
  await page.getByLabel('Arrival', { exact: true }).fill(arrival)
  await page.getByLabel('Departure', { exact: true }).fill(addDays(arrival, -1))
  await page.getByRole('button', { name: 'Find your room' }).click()
  await expect(page.getByText('Departure must be after arrival.')).toBeVisible()
  await page.getByLabel('Departure', { exact: true }).fill(addDays(arrival, 3))
  await page.getByRole('button', { name: 'Increase children' }).click()
  await expect(page.getByLabel('Children count')).toHaveText('1')
  await page.getByRole('button', { name: 'Find your room' }).click()
  await bookingStep(page, 'ROOMS')
  await expect(page.getByRole('heading', { name: 'Classic Double' })).toHaveCount(0)
  await expect(page.getByText('Demonstration availability and pricing.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: /^(Select|Selected) room: Alpine Comfort$/, exact: true }).click()
  await expect(page.getByRole('button', { name: /^(Select|Selected) room: Alpine Comfort$/, exact: true })).toHaveAttribute('aria-pressed', 'true')
  const summary = page.getByRole('complementary', { name: 'Your stay summary' })
  await expect(summary).toContainText(/EUR\s*456/)
  await shot(page, info, 'booking-rooms')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: 'Review your stay' }).click()
  await bookingStep(page, 'CHECKOUT')
  await expect(page.getByText('Demonstration checkout', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Complete reservation preview' }).click()
  await expect(page.getByText('Please acknowledge that this is a reservation preview.')).toBeVisible()
  await page.getByRole('button', { name: 'Use example guest details' }).click()
  await expect(page.getByLabel('Email (optional)', { exact: true })).toHaveValue('alex@example.com')
  await page.getByRole('checkbox').check()
  await shot(page, info, 'booking-checkout')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: 'Complete reservation preview' }).click()
  await bookingStep(page, 'COMPLETE')
  await expect(page.getByText('No booking has been placed.', { exact: false })).toBeVisible()
  await expect(page.getByText('DEMO-RG-000001', { exact: true })).toBeVisible()
  await expect(page.locator('[aria-labelledby="confirmation-heading"]')).toContainText(/EUR\s*456/)
  await shot(page, info, 'booking-complete')
  await expect(page.locator('input[type="password"],input[autocomplete^="cc-"]')).toHaveCount(0)
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  expect(writes).toEqual([])
  await page.getByRole('button', { name: 'Plan another stay' }).click()
  await bookingStep(page, 'STAY')
  await page.getByLabel('Arrival', { exact: true }).fill(closedDate)
  await page.getByLabel('Departure', { exact: true }).fill(addDays(closedDate, 1))
  await page.getByRole('button', { name: 'Find your room' }).click()
  await expect(page.getByRole('button', { name: 'Choose other dates' })).toBeVisible()
  await page.getByRole('button', { name: 'Choose other dates' }).click()
  await bookingStep(page, 'STAY')
})

test('all hotel URLs, invalid identifiers and back navigation are coherent', async ({ page }) => {
  for (const [id, name] of [['agnes', 'Agnes'], ['spalloni', 'Spalloni'], ['schiebel', 'Schiebel']]) {
    await page.goto(`/book?hotel=${id}`)
    await expect(page.getByRole('radio', { name: new RegExp(name) })).toBeChecked()
  }
  await page.goto('/book?hotel=unknown')
  await expect(page.locator('input[name="hotel"]:checked')).toHaveCount(0)
  await page.getByRole('button', { name: 'Find your room' }).click()
  await expect(page.getByText('Choose one of our three alpine homes.')).toBeVisible()
  await page.getByRole('radio', { name: /Agnes/ }).check()
  await expect(page).toHaveURL(/hotel=agnes/)
  await page.getByRole('radio', { name: /Spalloni/ }).check()
  await page.goBack()
  await expect(page.getByRole('radio', { name: /Agnes/ })).toBeChecked()
})

