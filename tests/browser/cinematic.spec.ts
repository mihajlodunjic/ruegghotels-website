import { test, expect, type Page, type TestInfo } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdir } from 'node:fs/promises'
const root = process.env.RUEGG_EVIDENCE_ROOT || 'docs/evidence/package-04'
const state = (page: Page, mode: string) => expect(page.locator('main')).toHaveAttribute('data-state', mode)
const shot = async (page: Page, info: TestInfo, name: string) => {
  await expect(page.locator('main')).toHaveAttribute('data-ui-ready', 'true')
  await expect(page.locator('main')).toHaveAttribute('data-visual-ready', 'true')
  await page.evaluate(() => document.fonts.ready)
  await mkdir(root, { recursive: true })
  await page.screenshot({ path: `${root}/${info.project.name}-home-${name}.png`, fullPage: false, animations: 'disabled' })
}

test('desktop cinematic canvas covers wide and tall screens without letterboxing', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'one desktop viewport geometry check')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const [width, height] of [[1740, 864], [1440, 900], [1920, 1080]]) {
    await page.setViewportSize({ width, height })
    await page.goto('/')
    await expect(page.getByTestId('media-frame')).toBeVisible()
    const frame = await page.getByTestId('media-frame').boundingBox()
    const plane = await page.getByTestId('source-plane').boundingBox()
    expect(frame).not.toBeNull()
    expect(plane).not.toBeNull()
    expect(frame!.x).toBeCloseTo(0, 0)
    expect(frame!.y).toBeCloseTo(0, 0)
    expect(frame!.width).toBeCloseTo(width, 0)
    expect(frame!.height).toBeCloseTo(height, 0)
    expect(plane!.x).toBeLessThanOrEqual(frame!.x + 1)
    expect(plane!.y).toBeLessThanOrEqual(frame!.y + 1)
    expect(plane!.x + plane!.width).toBeGreaterThanOrEqual(width - 1)
    expect(plane!.y + plane!.height).toBeGreaterThanOrEqual(height - 1)
    expect(plane!.width / plane!.height).toBeCloseTo(16 / 9, 3)
  }
  // The existing room-information split still uses its deliberate 64vw media frame.
  await page.setViewportSize({ width: 1740, height: 864 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Step inside' }).click()
  await page.getByRole('button', { name: 'Continue the journey' }).click()
  await page.getByRole('button', { name: /^Explore Room$/i }).click()
  const infoFrame = await page.getByTestId('media-frame').boundingBox()
  expect(infoFrame).not.toBeNull()
  expect(infoFrame!.width / 1740).toBeCloseTo(.64, 2)
  expect(infoFrame!.width / infoFrame!.height).toBeCloseTo(16 / 9, 2)
})

test('approved master → room V3 → reverse → hallway → genuine finale', async ({ page }, info) => {
  const errors: string[] = []
  const media: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'warning' && message.text().includes('GSAP target')) errors.push(message.text()) })
  page.on('request', (request) => { if (request.url().includes('.mp4')) media.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Step inside' })).toBeVisible()
  // The Master can preload before the user starts; room and reverse clips must remain on demand.
  expect(media.every((url) => url.includes('master-1080.v1.mp4'))).toBe(true)
  await shot(page, info, 'invitation')
  await page.getByRole('button', { name: 'Step inside' }).click()
  await state(page, 'WELCOME_PAUSED')
  expect(Math.abs(await page.getByTestId('master-video').evaluate((v: HTMLVideoElement) => v.currentTime) - 10)).toBeLessThan(.125)
  expect(Math.abs(Number(await page.getByTestId('source-plane').getAttribute('data-frame-time')) - 10)).toBeLessThan(2 / 24)
  await shot(page, info, 'welcome')
  await page.getByRole('button', { name: 'Menu', exact: false }).click()
  await expect(page.getByRole('dialog')).toHaveAttribute('data-menu-ready', 'true')
  await shot(page, info, 'menu')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Continue the journey' }).click()
  await state(page, 'HALLWAY_PAUSED')
  expect(Math.abs(await page.getByTestId('master-video').evaluate((v: HTMLVideoElement) => v.currentTime) - 17.125)).toBeLessThan(.125)
  expect(Math.abs(Number(await page.getByTestId('source-plane').getAttribute('data-frame-time')) - 17.125)).toBeLessThan(2 / 24)
  await shot(page, info, 'hallway')
  const box = await page.getByTestId('source-plane').boundingBox()
  expect(box!.width / box!.height).toBeCloseTo(16 / 9, 3)
  if (info.project.name.includes('mobile')) {
    const frame = await page.getByTestId('media-frame').boundingBox()
    expect(frame!.height).toBe(page.viewportSize()!.height)
    const door = await page.getByRole('button', { name: 'Explore room through the right door' }).boundingBox()
    expect(door!.x).toBeGreaterThan(0); expect(door!.x + door!.width).toBeLessThan(page.viewportSize()!.width)
  }
  await page.getByRole('button', { name: 'Explore room through the right door' }).click()
  await state(page, 'ROOM_AT_B3')
  // Reverse may warm only after B3 is decoded and on screen.
  await shot(page, info, 'room-b3')
  await page.getByRole('button', { name: 'About this room' }).click()
  await state(page, 'ROOM_INFO_OPEN')
  await shot(page, info, 'room-info')
  await page.getByRole('button', { name: 'Back to hallway' }).click()
  await state(page, 'ROOM_AT_B3')
  await expect(page.getByTestId('branch-video')).toHaveJSProperty('paused', true)
  await state(page, 'ROOM_EXITING')
  await expect(page.getByRole('button', { name: 'Close room information' })).toHaveCount(0)
  await state(page, 'HALLWAY_PAUSED')
  expect(media.some((url) => url.includes('room-reverse'))).toBe(true)
  expect(await page.locator('video').evaluateAll((videos) => videos.filter((video) => !(video as HTMLVideoElement).paused).length)).toBe(0)
  await page.getByRole('button', { name: 'Continue to the table' }).click()
  await state(page, 'FINALE')
  expect(Math.abs(await page.getByTestId('master-video').evaluate((v: HTMLVideoElement) => v.currentTime) - 23.375)).toBeLessThan(.125)
  expect(Math.abs(Number(await page.getByTestId('source-plane').getAttribute('data-frame-time')) - 23.375)).toBeLessThan(2 / 24)
  await shot(page, info, 'finale')
  await expect(page.getByRole('link', { name: 'Design Your Alpine Experience', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Discover RÜEGG Passport', exact: true })).toBeVisible()
  for (const hotel of ['agnes', 'spalloni', 'schiebel']) await expect(page.locator(`a[href="/book?hotel=${hotel}"]`)).toBeVisible()
  await page.locator('a[href="/book?hotel=spalloni"]').click()
  await expect(page).toHaveURL(/book\?hotel=spalloni$/)
  await expect(page.getByRole('radio', { name: /Spalloni/ })).toBeChecked()
  await expect(page.getByRole('button', { name: 'Find your room' })).toBeVisible()
  await page.goBack()
  await state(page, 'INVITATION')
  expect(await page.locator('video').count()).toBe(2)
  expect(errors).toEqual([])
})

