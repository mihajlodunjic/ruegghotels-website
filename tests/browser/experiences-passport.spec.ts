test('passport remains interactive when browser storage is unavailable', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Unavailable', 'SecurityError') } }))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/passport')
  await expect(page.getByText('Your stamps are available for this visit.', { exact: false })).toBeVisible()
  for (const name of ['Agnes', 'Spalloni', 'Johann']) await page.getByRole('button', { name: `Collect demo stamp for ${name}`, exact: true }).click()
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '3')
  await page.getByRole('button', { name: 'Open your three alpine chapters' }).click()
  await expect(page.locator('[data-reward-chapter]')).toHaveCount(3)
  await page.getByRole('button', { name: 'Reset demo passport' }).click()
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '0')
})
