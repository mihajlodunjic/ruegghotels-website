const root = process.env.RUEGG_EVIDENCE_ROOT || 'docs/evidence/package-03-5'
function summerDate() { let day = addDays(todayISO(), 30); while (![6, 7, 8].includes(Number(day.slice(5, 7)))) day = addDays(day, 1); return day }
const phase = (page: Page, step: string) => expect(page.locator('[data-planner-step]')).toHaveAttribute('data-planner-step', step)
async function ready(page: Page) {
  const shell = page.locator('[data-page-ready]')
  if (await shell.count()) await expect(shell).toHaveAttribute('data-page-ready', 'true')
  const step = page.locator('[data-step-ready]')
  if (await step.count()) await expect(step).toHaveAttribute('data-step-ready', 'true')
  const passport = page.locator('[data-passport-ready]')
  if (await passport.count()) await expect(passport).toHaveAttribute('data-passport-ready', 'true')
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function shot(page: Page, info: TestInfo, name: string, selector?: string) {
  if (!['desktop', 'mobile'].includes(info.project.name)) return
  await ready(page); await mkdir(root, { recursive: true })
  if (selector) await page.locator(selector).screenshot({ path: `${root}/${info.project.name}-${name}.png`, animations: 'disabled' })
  else await page.screenshot({ path: `${root}/${info.project.name}-${name}.png`, fullPage: true, animations: 'disabled' })
}
async function accessible(page: Page) { await ready(page); expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]) }

