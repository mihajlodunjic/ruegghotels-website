test('passport collects, persists, unlocks real chapter content and resets', async ({ page }, info) => {
  await page.goto('/passport')
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '0')
  await shot(page, info, 'passport-empty')
  await accessible(page)
  await page.getByRole('button', { name: 'Collect demo stamp for Agnes', exact: true }).click()
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '1')
  await expect(page.getByRole('button', { name: 'Demo stamp collected for Agnes', exact: true })).toBeDisabled()
  const next = page.getByRole('region', { name: /A place still/ })
  await expect(next.locator('a[href="/book?hotel=agnes"]')).toHaveCount(0)
  await expect(next.locator('a[href="/book?hotel=spalloni"]')).toBeVisible()
  await shot(page, info, 'passport-partial', '#your-passport')
  await page.reload()
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '1')
  expect(await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!), PASSPORT_KEY)).toEqual({ version: 1, stamps: ['agnes'] })
  await page.getByRole('button', { name: 'Collect demo stamp for Spalloni', exact: true }).click()
  await page.getByRole('button', { name: 'Collect demo stamp for Johann', exact: true }).click()
  await expect(page.locator('[data-reward-unlocked]')).toHaveAttribute('data-reward-unlocked', 'true')
  await page.getByRole('button', { name: 'Open your three alpine chapters' }).click()
  await expect(page.locator('[data-reward-chapter]')).toHaveCount(3)
  for (const [id, town] of [['agnes', 'Kandersteg'], ['spalloni', 'Splügen'], ['schiebel', 'Oberstdorf']]) await expect(page.getByRole('link', { name: `Plan your ${town} chapter` })).toHaveAttribute('href', new RegExp(`^/experiences\\?hotel=${id}&`))
  await shot(page, info, 'passport-complete')
  await accessible(page)
  await page.getByTestId('passport-schiebel').getByRole('link', { name: 'Stay with Johann' }).click()
  await expect(page.getByRole('radio', { name: /Johann/ })).toBeChecked()
  await page.goBack()
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '3')
  await page.getByRole('button', { name: 'Reset demo passport' }).click()
  await expect(page.locator('[data-passport-count]')).toHaveAttribute('data-passport-count', '0')
  await expect(page.locator('[data-reward-unlocked]')).toHaveAttribute('data-reward-unlocked', 'false')
  expect(await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!), PASSPORT_KEY)).toEqual({ version: 1, stamps: [] })
})

